export function moonGuide(id: RoleId): Notes & { context: string } {
  if (id in newGuides) return { ...newGuides[id as keyof typeof newGuides], context: contexts[id] };
  if (id in sharedViolet) return { ...sharedViolet[id as keyof typeof sharedViolet], context: contexts[id] };

  const role = troubleRoles.find(({ img }) => img === id);
  if (!role) throw new Error(`Missing Once in a Blue Moon guide: ${id}`);
  const notes = sharedTrouble[id as keyof typeof sharedTrouble];
  return {
    timing: role.when,
    example: troubleExamples[role.slug],
    ...notes,
    context: contexts[id],
  };
}
